export function Illustration({ id }: { id?: string }) {
  if (!id) return null;
  const Icon = ICONS[id];
  if (!Icon) return null;
  return (
    <div className="illustration" aria-hidden>
      <Icon absoluteStrokeWidth strokeWidth={1.75} />
    </div>
  );
}

